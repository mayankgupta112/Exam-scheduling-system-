/* ---------- the AI seat allocator ----------
   1. Works out how many shifts are needed: registered candidates / seats per shift across all centres.
   2. Round 1: every candidate is tried at their 1st preference (first registered, first served), then round 2 for 2nd preference.
   3. Anyone still unplaced gets the nearest centre with space (same district, then same state, then the emptiest centre).
   4. Seats fill shift 1 first, then shift 2, and so on. Already allocated candidates are never touched. */
/* Clash handling: only candidates who clash (other exam on the same day, or reported from the date slip) are moved to another exam day,
   and only when the clashes on that day reach the admin's threshold. Everyone else keeps their date.
   A clashing candidate takes a free seat at the same centre on another day; if none is free, swaps seats with a non-clashing candidate. */
const dayDiff = (a, b) => Math.abs((new Date(a) - new Date(b)) / 864e5);
const freeN = (cen, exam, s, cap) => { const u = new Set(db.prepare("SELECT n FROM allocations WHERE cen=? AND exam=? AND shift=?").all(cen, exam, s).map((x) => x.n)); if (u.size >= cap) return null; let n = 1; while (u.has(n)) n++; return n; };
function clashEntries(ex) {
  return db.prepare("SELECT a.id aid,a.cand,a.cen,a.shift,c.other_date od,EXISTS(SELECT 1 FROM clash_requests r WHERE r.cand=a.cand AND r.exam=a.exam) req FROM allocations a JOIN candidates c ON c.id=a.cand WHERE a.exam=?").all(ex.id)
    .map((r) => ({ ...r, date: shiftInfo(ex, r.shift).date })).filter((r) => r.req || r.od === r.date);
}
function moveOffDate(ex, e) {
  const per = shiftInfo(ex, 1).perDay, smax = Math.min(MAX_SHIFTS, Math.max(ex.shifts || 1, (ex.exam_days || 1) * per));
  const c = db.prepare("SELECT * FROM centres WHERE id=?").get(e.cen); if (!c) return "stuck";
  const slots = [];
  for (let s = 1; s <= smax; s++) { const d = shiftInfo(ex, s).date; if (d !== e.date && d !== e.od) slots.push({ s, d }); }
  slots.sort((x, y) => dayDiff(x.d, e.date) - dayDiff(y.d, e.date) || x.s - y.s);
  const code = (s, n) => `${c.code}-S${s}-${String(n).padStart(4, "0")}`, done = () => db.prepare("DELETE FROM clash_requests WHERE cand=? AND exam=?").run(e.cand, ex.id);
  for (const t of slots) {
    const n = freeN(c.id, ex.id, t.s, c.cap);
    if (n) { db.prepare("UPDATE allocations SET shift=?,n=?,seat=?,dnote=? WHERE id=?").run(t.s, n, code(t.s, n), `Your exam day was moved from ${e.date} to ${t.d} because of a clash with another exam.`, e.aid); done(); return "moved"; }
  }
  for (const t of slots) {
    const b = db.prepare(`SELECT a.id,a.n,a.shift FROM allocations a JOIN candidates c ON c.id=a.cand WHERE a.cen=? AND a.exam=? AND a.shift=? AND COALESCE(c.other_date,'')!=?
      AND NOT EXISTS (SELECT 1 FROM clash_requests r WHERE r.cand=a.cand AND r.exam=a.exam) LIMIT 1`).get(c.id, ex.id, t.s, e.date);
    if (b) {
      db.prepare("UPDATE allocations SET n=-1 WHERE id=?").run(e.aid);
      db.prepare("UPDATE allocations SET shift=?,n=?,seat=?,dnote=? WHERE id=?").run(e.shift, e.n_, code(e.shift, e.n_), `Your exam day was adjusted to ${e.date}.`, b.id);
      db.prepare("UPDATE allocations SET shift=?,n=?,seat=?,dnote=? WHERE id=?").run(t.s, b.n, code(t.s, b.n), `Your exam day was moved from ${e.date} to ${t.d} because of a clash with another exam.`, e.aid);
      done(); return "swapped";
    }
  }
  return "stuck";
}
function applyClashes(examId) {
  const ex = db.prepare("SELECT * FROM exams WHERE id=?").get(examId), out = { moved: 0, swapped: 0, stuck: 0 };
  if (!ex || !ex.date || !(ex.threshold > 0)) return out;
  const by = {};
  for (const e of clashEntries(ex)) { e.n_ = db.prepare("SELECT n FROM allocations WHERE id=?").get(e.aid).n; (by[e.date] ??= []).push(e); }
  for (const d in by) if (by[d].length >= ex.threshold) for (const e of by[d]) { e.n_ = db.prepare("SELECT n FROM allocations WHERE id=?").get(e.aid).n; const r = moveOffDate(ex, e); out[r]++; }
  db.prepare("UPDATE exams SET shifts=MAX(COALESCE(shifts,0),COALESCE((SELECT MAX(shift) FROM allocations WHERE exam=?),0)) WHERE id=?").run(examId, examId);
  return out;
}
function runAI(examId) {
  return db.transaction(() => {
    let ex = db.prepare("SELECT * FROM exams WHERE id=?").get(examId);
    if (!ex) throw new Bad("Select an examination.");
    if (!planOk(ex)) throw new Bad("Set the exam schedule first (date, start time, duration).");
    const cens = db.prepare("SELECT * FROM centres ORDER BY name").all();
    if (!cens.length) throw new Bad("Add exam centres first.");
    const totalCap = cens.reduce((s, c) => s + c.cap, 0);
    const cands = db.prepare("SELECT * FROM candidates c WHERE exam=? AND NOT EXISTS (SELECT 1 FROM allocations a WHERE a.cand=c.id AND a.exam=c.exam) ORDER BY created, reg").all(examId);
    const existing = db.prepare("SELECT cen,shift,n FROM allocations WHERE exam=?").all(examId);
    const S = Math.max(ex.shifts || 1, Math.ceil((existing.length + cands.length) / totalCap));
    if (S > MAX_SHIFTS) throw new Bad(`This exam needs ${S} shifts (limit ${MAX_SHIFTS}). Add more centres or increase seats per shift.`);
    const used = {}, rem = {};
    const slot = (cid, s) => ((used[cid] ??= {})[s] ??= new Set());
    for (const c of cens) rem[c.id] = c.cap * S;
    for (const a of existing) { slot(a.cen, a.shift).add(a.n); if (rem[a.cen] != null) rem[a.cen]--; }
    const take = (c) => {
      if (rem[c.id] <= 0) return null;
      for (let s = 1; s <= S; s++) { const u = slot(c.id, s); if (u.size < c.cap) { let n = 1; while (u.has(n)) n++; u.add(n); rem[c.id]--; return { shift: s, n }; } }
      return null;
    };
    const byId = Object.fromEntries(cens.map((c) => [c.id, c])), out = [];
    let pending = cands.map((cd) => ({ cd, prefs: JSON.parse(cd.prefs) }));
    for (let r = 0; r < 2; r++) pending = pending.filter(({ cd, prefs }) => {
      const c = byId[prefs[r]], t = c && take(c);
      if (t) { out.push({ cd, c, ...t, pref: r + 1 }); return false; } return true;
    });
    const low = (x) => String(x || "").trim().toLowerCase();
    for (const { cd } of pending) {
      const rank = (c) => (low(c.state) === low(cd.state) ? (low(c.district) === low(cd.district) ? 0 : 1) : 2);
      const c = cens.filter((x) => rem[x.id] > 0).sort((a, b) => rank(a) - rank(b) || rem[b.id] - rem[a.id])[0], t = c && take(c);
      if (t) out.push({ cd, c, ...t, pref: 0 });
    }
    const ins = db.prepare("INSERT INTO allocations(id,cand,exam,cen,shift,n,seat,pref) VALUES(?,?,?,?,?,?,?,?)");
    for (const o of out) ins.run(uid(), o.cd.id, examId, o.c.id, o.shift, o.n, `${o.c.code}-S${o.shift}-${String(o.n).padStart(4, "0")}`, o.pref);
    db.prepare("UPDATE exams SET shifts=?,alloc_done=1,alloc_note=NULL WHERE id=?").run(S, examId);
    const sw = applyClashes(examId);
    const per = shiftInfo(ex, 1).perDay;
    return { swaps: sw, shifts: S, perShiftSeats: totalCap, perDay: per, days: Math.ceil(S / per), firstDate: ex.date, lastDate: shiftInfo(ex, S).date,
      allocated: out.length, waiting: cands.length - out.length, first: out.filter((o) => o.pref === 1).length, second: out.filter((o) => o.pref === 2).length,
      nearest: out.filter((o) => o.pref === 0).length, perCentre: cens.map((c) => ({ name: c.name, used: c.cap * S - rem[c.id], total: c.cap * S })) };
  })();
}
admin.post("/allocate", h((r) => runAI(r.body.exam)));
admin.put("/allocations/:id/move", h((r) => db.transaction(() => {
  const a = db.prepare("SELECT * FROM allocations WHERE id=?").get(r.params.id), c = db.prepare("SELECT * FROM centres WHERE id=?").get(r.body.cen);
  if (!a || !c) throw new Bad("Select a centre.");
  if (a.cen === c.id) throw new Bad("Candidate is already at this centre.");
  const S = Math.max(db.prepare("SELECT shifts FROM exams WHERE id=?").get(a.exam).shifts || 1, 1);
  let f = null;
  for (let s = 1; s <= S && !f; s++) {
    const u = new Set(db.prepare("SELECT n FROM allocations WHERE cen=? AND exam=? AND shift=?").all(c.id, a.exam, s).map((x) => x.n));
    if (u.size < c.cap) { let n = 1; while (u.has(n)) n++; f = { shift: s, n }; }
  }
  if (!f) throw new Bad(`${c.name} is full in all ${S} shifts.`);
  const old = db.prepare("SELECT name FROM centres WHERE id=?").get(a.cen), moved = JSON.parse(a.moved); moved.push(old ? old.name : "removed centre");
  const seat = `${c.code}-S${f.shift}-${String(f.n).padStart(4, "0")}`;
  db.prepare("UPDATE allocations SET cen=?,shift=?,n=?,seat=?,pref=0,moved=? WHERE id=?").run(c.id, f.shift, f.n, seat, JSON.stringify(moved), a.id);
  return { seat };
})()));

